// Package pagetests is the Tests page block: a long effort the party makes
// (a montage, a chase, a negotiation) and the result it ended in.
//
// A test belongs to one page and holds the DM's list of possible results,
// an optional tally of successes and failures with the totals that end it,
// and the result recorded once the table settles it, stamped with the
// campaign calendar's date. Results are the DM's own words; a game system
// may offer its list as a starting point, but nothing here knows any game's
// rules. A recorded result is what an encounter's versions read to pick
// which version is played.
//
// Everything is the DM's unless a test is marked shown: then players see its
// name and the recorded result, and nothing else.
